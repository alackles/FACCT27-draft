#!/usr/bin/env bash
# Regenerate the temporary GenAI appendix from the working files:
# an anonymized snapshot of CLAUDE.md and notes/genai-log.md, converted
# to LaTeX by pandoc. Rerun at submission so the log is current.
#
#   scripts/genai-appendix.sh [outdir]    (default: sections/appendix)
set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$repo/sections/appendix}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# source file : output name
files=("CLAUDE.md:project-prompt" "notes/genai-log.md:genai-log")

anonymize() {
  sed -e 's/Acacia/Author A/g' -e 's/acacia/author-a/g' \
      -e 's/Elliott/Author B/g' -e 's/elliott/author-b/g' \
      -e 's#github\.com/alackles#github.com/[anonymized]#g'
}

for pair in "${files[@]}"; do
  src=${pair%%:*} name=${pair##*:}
  anonymize < "$repo/$src" > "$tmp/$name.md"
done

# Pandoc sizes pipe-table columns by the dashes in the separator row;
# the log's default (equal) widths waste space on the Date column.
sed -i 's/^|---|---|---|---|$/|----|-----|--------------|----------|/' "$tmp/genai-log.md"

# Anything identifying left after substitution: stop before writing.
if grep -n -i -E 'acacia|elliott|ackles|whitson|lawrence|alackles' "$tmp"/*.md; then
  echo "Identifying string survived anonymization (above); nothing written." >&2
  exit 1
fi

# pdflatex handles these; anything else needs a \DeclareUnicodeCharacter
# in main.tex's preamble.
odd=$(cat "$tmp"/*.md | grep -oP '[^\x00-\x7F]' | sort -u \
      | grep -v -x -E '—|–|§|≤|‘|’|“|”|…' || true)
if [ -n "$odd" ]; then
  echo "Warning: characters pdflatex may reject:" $odd >&2
fi

mkdir -p "$out"
commit=$(git -C "$repo" rev-parse --short HEAD)
for pair in "${files[@]}"; do
  src=${pair%%:*} name=${pair##*:}
  state=$commit
  git -C "$repo" diff --quiet HEAD -- "$src" || state="$commit + uncommitted changes"
  {
    printf '%% GENERATED by scripts/genai-appendix.sh from %s (%s), %s.\n' \
      "$src" "$state" "$(date +%F)"
    printf '%% Do not edit; rerun the script.\n'
    pandoc -f markdown-auto_identifiers -t latex \
      --shift-heading-level-by=1 "$tmp/$name.md"
  } > "$out/$name.tex"
  echo "wrote $out/$name.tex"
done
