#!/usr/bin/env bash
# Regenerate the temporary GenAI appendix from the working files:
# a snapshot of CLAUDE.md (typeset verbatim, like a code listing) and
# notes/genai-log.md (converted to a LaTeX table by pandoc).
# Writes two versions: anon/ (names and repo links masked, leak-checked)
# and named/ (unchanged). main.tex picks one with \ifanon, which
# follows acmart's `anonymous' option. Rerun at submission so the log
# is current.
#
#   bash scripts/genai-appendix.sh [outdir]    (default: sections/appendix)
set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$repo/sections/appendix}
rel=${out#"$repo"/}    # \VerbatimInput paths resolve from main.tex's directory
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# source file : output name : how it's typeset
files=("CLAUDE.md:project-prompt:verbatim" "notes/genai-log.md:genai-log:pandoc")

anonymize() {
  sed -e 's/Acacia/Author A/g' -e 's/acacia/author-a/g' \
      -e 's/Elliott/Author B/g' -e 's/elliott/author-b/g' \
      -e 's#github\.com/alackles#github.com/[anonymized]#g'
}

variants=(anon named)
mkdir -p "$tmp/anon" "$tmp/named"
for entry in "${files[@]}"; do
  IFS=: read -r src name mode <<< "$entry"
  anonymize < "$repo/$src" > "$tmp/anon/$name.md"
  cp "$repo/$src" "$tmp/named/$name.md"
done

# Pandoc sizes pipe-table columns by the dashes in the separator row;
# the log's default (equal) widths waste space on the Date column.
sed -i 's/^|---|---|---|---|$/|----|-----|--------------|----------|/' \
  "$tmp"/{anon,named}/genai-log.md

# Anything identifying left after substitution: stop before writing.
if grep -n -i -E 'acacia|elliott|ackles|whitson|lawrence|alackles' "$tmp"/anon/*.md; then
  echo "Identifying string survived anonymization (above); nothing written." >&2
  exit 1
fi

# pdflatex handles these; anything else needs a \DeclareUnicodeCharacter
# in main.tex's preamble.
odd=$(cat "$tmp"/named/*.md | grep -oP '[^\x00-\x7F]' | sort -u \
      | grep -v -x -E '—|–|§|≤|‘|’|“|”|…' || true)
if [ -n "$odd" ]; then
  echo "Warning: characters pdflatex may reject:" $odd >&2
fi

commit=$(git -C "$repo" rev-parse --short HEAD)
for v in "${variants[@]}"; do
  mkdir -p "$out/$v"
  for entry in "${files[@]}"; do
    IFS=: read -r src name mode <<< "$entry"
    state=$commit
    git -C "$repo" diff --quiet HEAD -- "$src" || state="$commit + uncommitted changes"
    {
      printf '%% GENERATED by scripts/genai-appendix.sh from %s (%s, %s), %s.\n' \
        "$src" "$state" "$v" "$(date +%F)"
      printf '%% Do not edit; rerun the script.\n'
      if [ "$mode" = verbatim ]; then
        # Listing style is set by \fvset in main.tex's preamble.
        cp "$tmp/$v/$name.md" "$out/$v/$name.md"
        printf '\\subsection{\\texttt{%s}}\n' "$(basename "$src")"
        printf '\\VerbatimInput{%s/%s/%s.md}\n' "$rel" "$v" "$name"
      else
        pandoc -f markdown-auto_identifiers -t latex \
          --shift-heading-level-by=1 "$tmp/$v/$name.md"
      fi
    } > "$out/$v/$name.tex"
    echo "wrote $out/$v/$name.tex"
  done
done
